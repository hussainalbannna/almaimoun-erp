--  يُبدّل سياسة SELECT من «كل المصادَقين» إلى «حساب المالك فقط» — سريّة حقيقية على
--  مستوى القاعدة: حتى لو حاول موظف الوصول تقنيًا، تُرفض القراءة. الكتابة تبقى كما هي
