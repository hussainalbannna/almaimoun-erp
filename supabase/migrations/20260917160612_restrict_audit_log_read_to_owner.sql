DROP POLICY IF EXISTS audit_log_select ON public.audit_log;
CREATE POLICY audit_log_select ON public.audit_log
  FOR SELECT TO authenticated
  USING ( (auth.jwt() ->> 'email') = 'hussainalbannna@gmail.com' );
